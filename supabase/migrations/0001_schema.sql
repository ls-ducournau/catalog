-- Catalog v2 : schéma PostgreSQL multi-utilisateur.
-- Conception : specs/catalog-v2-donnees.md ; spec : specs/catalog-v2-rust-supabase.md (FR-3, FR-4, FR-5, FR-9).
--
-- Deux familles de tables :
--   - le catalogue partagé (catalog_titles, catalog_people) : ce qui vient de TMDB, commun à tous
--     les comptes, écrit seulement par le serveur ;
--   - les tables personnelles : chacune porte user_id, sa clé primaire commence par user_id, et
--     toute clé étrangère vers une autre table personnelle inclut user_id. Une ligne d'un compte
--     ne peut donc pas désigner une ligne d'un autre compte (contrainte structurelle, en plus des
--     règles d'accès de 0002_securite.sql).
--
-- Identifiants personnels : bigint, numérotés par compte (clé primaire (user_id, id)). Les lignes
-- importées de la v1 gardent leur identifiant v1 (tous inférieurs à 1 000 000) ; les nouvelles
-- lignes prennent leur numéro dans une suite qui commence à 1 000 000, ce qui préserve l'ordre
-- d'arrivée (le tri « ajouté » de la v1 suit l'identifiant).
--
-- Aucune trace de l'ancien service de notes : ni identifiant de page, ni date d'édition distante,
-- ni drapeau d'envoi, ni table d'état de synchronisation.

-- ---------------------------------------------------------------------------------------------
-- Catalogue partagé
-- ---------------------------------------------------------------------------------------------

create table public.catalog_titles (
  id bigint generated always as identity primary key,
  -- Un même numéro TMDB peut désigner un film et une série : la clé naturelle est le couple.
  type text not null check (type in ('Movie', 'TV Series')),
  tmdb_id integer not null check (tmdb_id > 0),
  imdb_id text,
  -- Titre français TMDB (à défaut, titre d'origine).
  name text not null check (name <> ''),
  -- Texte, comme en v1 : les séries ont des plages (« 2019 - 2023 », « 2024 - »).
  year text,
  poster_path text,
  -- Genres TMDB en anglais, tableau JSON de chaînes (filtre par genre, catégorie Documentaire).
  genres jsonb check (genres is null or jsonb_typeof(genres) = 'array'),
  director text,
  tmdb_rating double precision,
  vote_count integer check (vote_count is null or vote_count >= 0),
  -- null : synopsis pas encore cherché ; '' : cherché, TMDB n'en a pas (distinction de la v1).
  overview text,
  -- Caractéristiques du modèle de préférence (genres, mots-clés, distribution, réalisation...).
  tmdb_features jsonb check (tmdb_features is null or jsonb_typeof(tmdb_features) = 'object'),
  -- Disponibilité en France ; le JSON garde son fetchedAt, recopié dans availability_fetched_at
  -- par le serveur dans la même écriture, pour trouver les fiches à rafraîchir sans lire le JSON.
  watch_providers jsonb check (watch_providers is null or jsonb_typeof(watch_providers) = 'object'),
  availability_fetched_at timestamptz,
  release_info jsonb check (release_info is null or jsonb_typeof(release_info) = 'object'),
  release_fetched_at timestamptz,
  -- Bande-annonce retenue ; null = pas encore cherchée.
  trailer_info jsonb check (trailer_info is null or jsonb_typeof(trailer_info) = 'object'),
  created_at timestamptz not null default now(),
  -- Dernière écriture de la fiche (rafraîchissement TMDB).
  updated_at timestamptz not null default now(),
  constraint catalog_titles_tmdb_unique unique (type, tmdb_id)
);

comment on table public.catalog_titles is
  'Fiches TMDB partagées entre comptes (FR-4). Écrites par le serveur seulement. Aucune donnée personnelle.';

-- Filtre « genre = X » et catégorie Documentaire : genres @> '["Documentary"]'.
create index catalog_titles_genres_idx on public.catalog_titles using gin (genres jsonb_path_ops);
-- Rafraîchissement par lots des fiches anciennes (disponibilité, dates de sortie).
create index catalog_titles_availability_fetched_idx on public.catalog_titles (availability_fetched_at);
create index catalog_titles_release_fetched_idx on public.catalog_titles (release_fetched_at);

create table public.catalog_people (
  -- Identifiant TMDB de la personne, stable d'un titre à l'autre.
  id integer primary key check (id > 0),
  name text not null,
  profile_path text,
  updated_at timestamptz not null default now()
);

comment on table public.catalog_people is
  'Personnes TMDB partagées (nom, photo). Les scores et avis sont dans person_scores et person_opinions.';

-- ---------------------------------------------------------------------------------------------
-- Bibliothèque personnelle : le rapport d'un compte à un titre
-- ---------------------------------------------------------------------------------------------

create table public.library_items (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id bigint generated by default as identity (start with 1000000),
  -- Fiche partagée ; null pour un titre sans identifiant TMDB (saisi à la main en v1).
  title_id bigint references public.catalog_titles (id) on delete restrict,
  -- Titre sans fiche partagée : ses informations restent personnelles, jamais dans le catalogue.
  local_name text,
  local_type text check (local_type in ('Movie', 'TV Series')),
  local_year text,
  local_genres jsonb check (local_genres is null or jsonb_typeof(local_genres) = 'array'),
  watch_status text not null default 'Unwatched' check (watch_status in ('Watched', 'Unwatched')),
  -- Note personnelle : 0 (💩) à 5 étoiles. L'API la rend sous la forme d'affichage de la v1.
  rating smallint check (rating between 0 and 5),
  -- '' (effacement volontaire) distinct de null (jamais renseigné), comme en v1.
  ressenti text,
  elo_score double precision not null default 1200,
  duels_count integer not null default 0 check (duels_count >= 0),
  last_duel_at timestamptz,
  -- Départage par palier (classement-v1) : ne vaut que pour la note tier_rating.
  tier_elo double precision not null default 1200,
  tier_duels_count integer not null default 0 check (tier_duels_count >= 0),
  tier_rating smallint check (tier_rating between 0 and 5),
  tier_band smallint check (tier_band in (0, 1, 2)),
  -- Doublon hérité de la v1 (même fiche TMDB deux fois dans la bibliothèque) : gardé à l'import
  -- pour ne rien perdre, exclu de la règle « un titre une fois par compte ».
  import_duplicate boolean not null default false,
  -- Écrit explicitement par le serveur (pas de déclencheur) : il relance l'entraînement du modèle.
  updated_at timestamptz not null default now(),
  primary key (user_id, id),
  constraint library_items_title_or_local check (
    (title_id is not null
      and local_name is null and local_type is null and local_year is null and local_genres is null)
    or (title_id is null and local_name is not null and local_name <> '' and local_type is not null)
  ),
  constraint library_items_duplicate_has_title check (not import_duplicate or title_id is not null)
);

comment on table public.library_items is
  'Rapport personnel à un titre : statut, note, Elo, départage. Remplace la partie personnelle de items (v1).';

-- Un titre au plus une fois par compte (ajout idempotent), doublons hérités exceptés.
create unique index library_items_one_per_title
  on public.library_items (user_id, title_id)
  where title_id is not null and not import_duplicate;
-- Pile à voir, titres vus éligibles aux duels, compteurs de l'accueil.
create index library_items_status_idx on public.library_items (user_id, watch_status);
-- Vérification de la clé étrangère depuis le catalogue (nettoyage des fiches orphelines).
create index library_items_title_idx on public.library_items (title_id);

-- Instantané des Elo avant la dernière réinitialisation (annulable), une génération par compte.
create table public.elo_snapshot (
  user_id uuid not null references auth.users (id) on delete cascade,
  item_id bigint not null,
  elo_score double precision not null,
  duels_count integer not null check (duels_count >= 0),
  last_duel_at timestamptz,
  primary key (user_id, item_id),
  foreign key (user_id, item_id) references public.library_items (user_id, id) on delete cascade
);

-- Duels de titres (Elo général).
create table public.duels (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id bigint generated by default as identity (start with 1000000),
  item_a_id bigint not null,
  item_b_id bigint not null,
  -- null : duel passé.
  winner_id bigint,
  elo_a_before double precision not null,
  elo_b_before double precision not null,
  elo_a_after double precision not null,
  elo_b_after double precision not null,
  created_at timestamptz not null default now(),
  primary key (user_id, id),
  foreign key (user_id, item_a_id) references public.library_items (user_id, id) on delete cascade,
  foreign key (user_id, item_b_id) references public.library_items (user_id, id) on delete cascade,
  constraint duels_distinct check (item_a_id <> item_b_id),
  constraint duels_winner_in_pair check (winner_id is null or winner_id in (item_a_id, item_b_id))
);

-- « Un duel plus récent a-t-il touché A ou B ? » (annulation) et suppression d'un titre.
create index duels_item_a_idx on public.duels (user_id, item_a_id);
create index duels_item_b_idx on public.duels (user_id, item_b_id);

-- Duels de départage v1.0 (classement-v1 FR-3) : plus écrits par la v1, gardés pour ne rien perdre.
create table public.tier_duels (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id bigint generated by default as identity (start with 1000000),
  item_a_id bigint not null,
  item_b_id bigint not null,
  winner_id bigint,
  rating smallint not null check (rating between 0 and 5),
  elo_a_before double precision not null,
  elo_b_before double precision not null,
  elo_a_after double precision not null,
  elo_b_after double precision not null,
  created_at timestamptz not null default now(),
  primary key (user_id, id),
  foreign key (user_id, item_a_id) references public.library_items (user_id, id) on delete cascade,
  foreign key (user_id, item_b_id) references public.library_items (user_id, id) on delete cascade,
  constraint tier_duels_winner_in_pair check (winner_id is null or winner_id in (item_a_id, item_b_id))
);

create index tier_duels_item_a_idx on public.tier_duels (user_id, item_a_id);
create index tier_duels_item_b_idx on public.tier_duels (user_id, item_b_id);

-- Départage v1.1 : une répartition ou un quatuor par ligne, avec l'état avant/après de chaque titre
-- (payload.items[].id = identifiant personnel du titre, dans l'espace du même compte).
create table public.tier_rounds (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id bigint generated by default as identity (start with 1000000),
  rating smallint not null check (rating between 0 and 5),
  kind text not null check (kind in ('band', 'quad')),
  payload jsonb not null check (jsonb_typeof(payload -> 'items') = 'array'),
  created_at timestamptz not null default now(),
  primary key (user_id, id)
);

