create table public.playlists (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id bigint generated by default as identity (start with 1000000),
  -- 1 à 60 caractères, sans espace en bord (playlists-v1 EC-1).
  name text not null check (char_length(name) between 1 and 60 and name = btrim(name)),
  description text check (description is null or char_length(description) between 1 and 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, id)
);

-- La dernière modifiée d'abord.
create index playlists_recent_idx on public.playlists (user_id, updated_at desc, id desc);

create table public.playlist_items (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  playlist_id bigint not null,
  item_id bigint not null,
  position integer not null check (position >= 0),
  added_at timestamptz not null default now(),
  primary key (user_id, playlist_id, item_id),
  foreign key (user_id, playlist_id) references public.playlists (user_id, id) on delete cascade,
  -- Un titre retiré de la bibliothèque quitte aussi les playlists (playlists-v1 FR-9).
  foreign key (user_id, item_id) references public.library_items (user_id, id) on delete cascade
);

create index playlist_items_item_idx on public.playlist_items (user_id, item_id);
create index playlist_items_order_idx on public.playlist_items (user_id, playlist_id, position, added_at);

-- « Pas celui-là » dans les suggestions d'une playlist (playlists-v2 FR-5).
create table public.playlist_suggestion_dismissals (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  playlist_id bigint not null,
  item_id bigint not null,
  primary key (user_id, playlist_id, item_id),
  foreign key (user_id, playlist_id) references public.playlists (user_id, id) on delete cascade,
  foreign key (user_id, item_id) references public.library_items (user_id, id) on delete cascade
);

create index playlist_suggestion_dismissals_item_idx on public.playlist_suggestion_dismissals (user_id, item_id);

-- ---------------------------------------------------------------------------------------------
-- Vue de lecture : une ligne par titre de la bibliothèque, avec les colonnes de l'ancienne table
-- items (sans celles du service de notes). security_invoker : la vue applique les règles d'accès
-- des tables qu'elle lit, celles de la personne qui l'interroge.
-- ---------------------------------------------------------------------------------------------

create view public.library_view with (security_invoker = true) as
select
  li.user_id,
  li.id,
  li.title_id,
  coalesce(c.name, li.local_name) as name,
  coalesce(c.type, li.local_type) as type,
  coalesce(c.year, li.local_year) as year,
  coalesce(c.genres, li.local_genres) as genres,
  c.tmdb_id,
  c.imdb_id,
  c.poster_path,
  c.director,
  c.tmdb_rating,
  c.vote_count,
  c.overview,
  c.tmdb_features,
  c.watch_providers,
  c.release_info,
  c.trailer_info,
  li.watch_status,
  li.rating,
  li.ressenti,
  li.elo_score,
  li.duels_count,
  li.last_duel_at,
  li.tier_elo,
  li.tier_duels_count,
  li.tier_rating,
  li.tier_band,
  li.import_duplicate,
  li.updated_at
from public.library_items li
left join public.catalog_titles c on c.id = li.title_id;

comment on view public.library_view is
  'Lecture seule : bibliothèque d''un compte jointe au catalogue partagé (security_invoker).';
