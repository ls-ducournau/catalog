create index person_duels_person_b_idx on public.person_duels (user_id, person_b_id);

create table public.person_elo_snapshot (
  user_id uuid not null references auth.users (id) on delete cascade,
  person_id integer not null,
  elo_score double precision not null,
  duels_count integer not null check (duels_count >= 0),
  last_duel_at timestamptz,
  primary key (user_id, person_id),
  foreign key (user_id, person_id) references public.person_scores (user_id, person_id) on delete cascade
);

-- Avis sur une personne (+1 aimée, -1 pas aimée) et note d'une personne aimée. Le nom est celui
-- envoyé avec l'avis, gardé ici : il ne nourrit jamais le catalogue partagé. Pas de clé étrangère
-- vers catalog_people : on peut donner un avis sur une personne absente des duels.
create table public.person_opinions (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  person_id integer not null check (person_id > 0),
  name text not null,
  opinion smallint not null check (opinion in (-1, 1)),
  rating smallint check (rating between 0 and 5),
  updated_at timestamptz not null default now(),
  primary key (user_id, person_id),
  constraint person_opinions_rating_if_liked check (rating is null or opinion = 1)
);

-- ---------------------------------------------------------------------------------------------
-- Journal, titres écartés, impressions, réglages
-- ---------------------------------------------------------------------------------------------

-- Journal des gestes. Le sujet reste textuel, sans clé étrangère : le journal doit survivre à la
-- suppression de ce qu'il décrit (un retrait de titre reste dans l'historique).
--   item, person, playlist : identifiant numérique (« 42 ») ; tmdb : « movie:603 » ou « tv:1399 ».
create table public.events (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id bigint generated by default as identity (start with 1000000),
  kind text not null check (kind in (
    'added', 'removed', 'rated', 'dismissed', 'undismissed', 'triage',
    'playlist_created', 'playlist_deleted', 'playlist_item_added', 'playlist_item_removed',
    'playlist_watched', 'playlist_rated', 'opened'
  )),
  subject_type text not null check (subject_type in ('item', 'tmdb', 'person', 'playlist')),
  subject_id text not null,
  context jsonb check (context is null or jsonb_typeof(context) = 'object'),
  created_at timestamptz not null default now(),
  primary key (user_id, id),
  constraint events_subject_format check (
    (subject_type in ('item', 'person', 'playlist') and subject_id ~ '^[1-9][0-9]*$')
    or (subject_type = 'tmdb' and subject_id ~ '^(movie|tv):[1-9][0-9]*$')
  )
);

create index events_kind_idx on public.events (user_id, kind);
-- Dernier geste par titre (lassitude) et gestes d'un sujet.
create index events_subject_idx on public.events (user_id, subject_type, subject_id, created_at);

-- « Ne plus me proposer ça ».
create table public.dismissals (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  subject_type text not null check (subject_type in ('item', 'tmdb')),
  subject_id text not null,
  created_at timestamptz not null default now(),
  primary key (user_id, subject_type, subject_id),
  constraint dismissals_subject_format check (
    (subject_type = 'item' and subject_id ~ '^[1-9][0-9]*$')
    or (subject_type = 'tmdb' and subject_id ~ '^(movie|tv):[1-9][0-9]*$')
  )
);

-- Titres montrés à l'écran, un par jour au plus (jour d'exposition : heure de Paris décalée de 4 h).
create table public.impressions (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  subject_type text not null check (subject_type in ('item', 'tmdb')),
  subject_id text not null,
  day date not null,
  surface text not null check (surface in ('pile', 'discover', 'tonight', 'home', 'triage')),
  primary key (user_id, subject_type, subject_id, day),
  constraint impressions_subject_format check (
    (subject_type = 'item' and subject_id ~ '^[1-9][0-9]*$')
    or (subject_type = 'tmdb' and subject_id ~ '^(movie|tv):[1-9][0-9]*$')
  )
);

-- Lecture des 42 derniers jours et purge au-delà de 90.
create index impressions_day_idx on public.impressions (user_id, day);

-- Réglages en clé/valeur JSON (ex. streaming_subscriptions : tableau d'identifiants de services).
create table public.settings (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  key text not null check (key <> ''),
  value jsonb not null,
  primary key (user_id, key)
);

